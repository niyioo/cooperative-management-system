from rest_framework import mixins, permissions, status, viewsets
from rest_framework.decorators import action
from rest_framework.exceptions import ValidationError
from rest_framework.response import Response

from apps.accounts.permissions import FINANCE_STAFF, IsFinanceStaff

from . import services
from .models import SavingsAccount, SavingsTransaction
from .serializers import SavingsAccountSerializer, SavingsTransactionSerializer


class SavingsAccountViewSet(viewsets.ReadOnlyModelViewSet):
    serializer_class = SavingsAccountSerializer
    permission_classes = [permissions.IsAuthenticated]

    def get_queryset(self):
        user = self.request.user
        queryset = SavingsAccount.objects.select_related('member').order_by('member__last_name')
        if user.role in FINANCE_STAFF:
            return queryset
        return queryset.filter(member__user=user)


class SavingsTransactionViewSet(mixins.ListModelMixin, mixins.RetrieveModelMixin, mixins.CreateModelMixin,
                                viewsets.GenericViewSet):
    """
    Transactions are permanent: no edit or delete. A member's request is
    approved or rejected by finance staff; staff entries apply immediately.
    """
    serializer_class = SavingsTransactionSerializer
    permission_classes = [permissions.IsAuthenticated]

    def get_queryset(self):
        user = self.request.user
        queryset = SavingsTransaction.objects.select_related('account__member').order_by('-created_at')
        status_filter = self.request.query_params.get('status')
        if status_filter:
            queryset = queryset.filter(status=status_filter.upper())
        if user.role in FINANCE_STAFF:
            return queryset
        return queryset.filter(account__member__user=user)

    def perform_create(self, serializer):
        user = self.request.user
        data = serializer.validated_data
        if user.role in FINANCE_STAFF:
            account = data.get('account')
            if account is None:
                raise ValidationError({"account": "Choose the member's savings account."})
        else:
            # Members can only ever post to their own account, whatever they send.
            account, _ = SavingsAccount.objects.get_or_create(member=user.member_profile)
        serializer.instance = services.record(
            account=account, txn_type=data['transaction_type'], amount=data['amount'], by=user,
            # References are always generated by the server, so they stay unique.
            description=data.get('description') or "",
        )

    @action(detail=True, methods=['post'], permission_classes=[IsFinanceStaff])
    def approve(self, request, pk=None):
        txn = services.approve(self.get_object(), by=request.user)
        return Response(SavingsTransactionSerializer(txn).data)

    @action(detail=True, methods=['post'], permission_classes=[IsFinanceStaff])
    def reject(self, request, pk=None):
        reason = (request.data.get('reason') or '').strip()
        if len(reason) < 5:
            return Response({"reason": "Give a reason of at least 5 characters."}, status=status.HTTP_400_BAD_REQUEST)
        txn = services.reject(self.get_object(), by=request.user, reason=reason)
        return Response(SavingsTransactionSerializer(txn).data)
